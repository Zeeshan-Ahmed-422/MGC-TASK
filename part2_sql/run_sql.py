"""
Runs Part 2 end to end against an in-memory DuckDB and writes results.md.

Usage (from the repo root):
    python part2_sql/run_sql.py

DuckDB needs no server and no setup - it is a library, like SQLite, so the reviewer
runs one pip install and one python command. What this script does:

  1. loads data/leads.csv verbatim into a staging table `leads_raw`;
  2. creates the real table from schema.sql;
  3. tries to insert the RAW dump into it, which the UNIQUE (crm_record_hash)
     constraint rejects - that failure is the point of the constraint, so the script
     shows it rather than hiding it;
  4. inserts the deduplicated + city-normalised rows, which succeeds;
  5. runs the three queries from queries.sql against the raw staging table and prints
     the results.
"""

import os
import re
import sys

import duckdb

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

_HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(_HERE, "..", "data", "leads.csv")
SCHEMA_PATH = os.path.join(_HERE, "schema.sql")
QUERIES_PATH = os.path.join(_HERE, "queries.sql")
RESULTS_PATH = os.path.join(_HERE, "results.md")

# The city normalisation, written once in SQL and reused for the insert into `leads`.
# Query 3 in queries.sql carries its own copy on purpose: the brief asks for the
# normalisation to be visible inside that query.
CITY_CASE = """
        CASE LOWER(TRIM(city))
            WHEN 'islamabad'  THEN 'Islamabad'
            WHEN 'isb'        THEN 'Islamabad'
            WHEN 'rawalpindi' THEN 'Rawalpindi'
            WHEN 'rwp'        THEN 'Rawalpindi'
            WHEN 'karachi'    THEN 'Karachi'
            WHEN 'khi'        THEN 'Karachi'
            WHEN 'lahore'     THEN 'Lahore'
            WHEN 'peshawar'   THEN 'Peshawar'
            WHEN 'faisalabad' THEN 'Faisalabad'
            WHEN 'multan'     THEN 'Multan'
            WHEN 'gujranwala' THEN 'Gujranwala'
            WHEN 'abbottabad' THEN 'Abbottabad'
            ELSE 'UNMAPPED: ' || COALESCE(city, '(null)')
        END
"""


def split_queries(sql_text):
    """Split queries.sql on the '-- @query: <title>' markers into (title, sql) pairs."""
    parts = re.split(r"^--\s*@query:\s*(.+)$", sql_text, flags=re.MULTILINE)
    return [(title.strip(), body.strip()) for title, body in zip(parts[1::2], parts[2::2])]


def table(rows, columns):
    """Render a result set as a markdown table (also readable in a terminal)."""
    widths = [len(c) for c in columns]
    str_rows = []
    for row in rows:
        cells = ["" if v is None else (f"{v:,}" if isinstance(v, int) else str(v)) for v in row]
        str_rows.append(cells)
        widths = [max(w, len(c)) for w, c in zip(widths, cells)]
    out = ["| " + " | ".join(c.ljust(w) for c, w in zip(columns, widths)) + " |",
           "|" + "|".join("-" * (w + 2) for w in widths) + "|"]
    for cells in str_rows:
        out.append("| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths)) + " |")
    return "\n".join(out)


def main():
    report = ["# Part 2 - SQL output", "",
              "Generated by `python part2_sql/run_sql.py` (DuckDB, in-memory).", ""]

    con = duckdb.connect()  # in-memory; nothing is written to disk

    # ---- 1. raw staging table, straight from the CSV --------------------------
    con.execute(f"CREATE TABLE leads_raw AS SELECT * FROM read_csv_auto('{CSV_PATH}', header=true)")
    raw_rows = con.execute("SELECT COUNT(*) FROM leads_raw").fetchone()[0]
    distinct_hashes = con.execute("SELECT COUNT(DISTINCT crm_record_hash) FROM leads_raw").fetchone()[0]
    distinct_cities = con.execute("SELECT COUNT(DISTINCT city) FROM leads_raw").fetchone()[0]
    print(f"Loaded leads_raw: {raw_rows:,} rows, {distinct_hashes:,} distinct crm_record_hash, "
          f"{distinct_cities} distinct city spellings")
    report += [f"**Staging table `leads_raw`:** {raw_rows:,} rows, {distinct_hashes:,} distinct "
               f"`crm_record_hash`, {distinct_cities} distinct city spellings.", ""]

    # ---- 2. the real table ---------------------------------------------------
    with open(SCHEMA_PATH, encoding="utf-8") as fh:
        con.execute(fh.read())
    print("Created table `leads` from schema.sql")

    # ---- 3. prove the UNIQUE constraint blocks the duplicates ----------------
    # Everything except the dedup is identical to the good insert below, so the only
    # reason this fails is the duplicate crm_record_hash values.
    select_columns = f"""
        lead_id, CAST(created_at AS TIMESTAMP), source, city AS city_raw,
        {CITY_CASE} AS city_normalized,
        area, property_type, budget_pkr_lac, CAST(bedrooms AS SMALLINT),
        CAST(first_response_minutes AS INTEGER), calls_made,
        CAST(total_call_seconds AS INTEGER), whatsapp_replies, site_visits,
        agent_experience_years, CAST(is_overseas AS BOOLEAN),
        CAST(referred_by_existing_client AS BOOLEAN),
        CAST(has_financing_approved AS BOOLEAN), token_amount_received_pkr,
        crm_record_hash, CAST(converted AS BOOLEAN)
    """
    try:
        con.execute(f"INSERT INTO leads SELECT {select_columns} FROM leads_raw")
        print("UNEXPECTED: the raw insert succeeded - the UNIQUE constraint is not doing its job")
        report += ["**Unexpected:** inserting the raw dump succeeded; the UNIQUE constraint "
                   "should have rejected it.", ""]
    except duckdb.ConstraintException as exc:
        msg = str(exc).strip().split("\n")[0]
        print(f"Raw insert correctly REJECTED by the schema: {msg}")
        report += ["## Schema-level duplicate prevention", "",
                   "Inserting the raw dump into `leads` is rejected by "
                   "`UNIQUE (crm_record_hash)`:", "", "```", msg, "```", "",
                   "That is the constraint doing its job: the same lead entered twice by two "
                   "agents cannot be stored twice, so query 2's dedup never has to run in the "
                   "first place.", ""]

    # ---- 4. insert the canonical rows ---------------------------------------
    con.execute(f"""
        INSERT INTO leads
        SELECT {select_columns}
        FROM (
            SELECT *, ROW_NUMBER() OVER (
                       PARTITION BY crm_record_hash
                       ORDER BY created_at, LENGTH(lead_id), lead_id
                   ) AS rn
            FROM leads_raw
        )
        WHERE rn = 1
    """)
    loaded = con.execute("SELECT COUNT(*) FROM leads").fetchone()[0]
    print(f"Inserted {loaded:,} canonical rows into `leads` "
          f"({raw_rows - loaded} duplicates dropped); all CHECK constraints passed")
    report += [f"**Table `leads`:** {loaded:,} rows loaded after deduplication "
               f"({raw_rows - loaded} duplicate rows dropped). Every `CHECK` constraint "
               f"(source, city, property_type, non-negative counts, date range) passed, which "
               f"is itself a validation of the dump.", ""]

    # ---- 5. the three queries -----------------------------------------------
    with open(QUERIES_PATH, encoding="utf-8") as fh:
        queries = split_queries(fh.read())

    for title, sql in queries:
        print(f"\n{'=' * 78}\n{title}\n{'=' * 78}")
        cur = con.execute(sql)
        columns = [d[0] for d in cur.description]
        rows = cur.fetchall()
        rendered = table(rows, columns)
        print(rendered)
        report += [f"## {title}", "", rendered, ""]

        # Guard rail on query 3: a city spelling we never mapped must not pass silently.
        if title.startswith("3."):
            unmapped = [r for r in rows if str(r[0]).startswith("UNMAPPED")]
            verdict = ("All city spellings mapped; "
                       f"{len(rows)} distinct cities after normalisation.") if not unmapped else \
                      f"WARNING: unmapped city values: {unmapped}"
            print(verdict)
            report += [f"_{verdict}_", ""]

    with open(RESULTS_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(report))
    print(f"\nWrote {RESULTS_PATH}")


if __name__ == "__main__":
    main()
